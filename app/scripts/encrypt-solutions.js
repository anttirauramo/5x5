#!/usr/bin/env node
/**
 * encrypt-solutions.js
 *
 * Encrypts solution files from scripts/solutions/ and copies wordlist .txt files
 * from scripts/wordlists/ into app/assets/ for bundling with the React Native app.
 *
 * Usage: node scripts/encrypt-solutions.js
 * (run from app/ directory)
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// AES-256-CBC encryption key (32 bytes hex = 64 chars)
// This key is shared between this script and the app's runtime decryption.
// It prevents casual reading of solution files but is not a strong DRM.
const ENCRYPTION_KEY = '4f6b7a9c2e1d8f3a5b0c7d4e9f2a1b6c8d3e0f5a7b9c4d2e1f8a3b6c0d5e7f9a';
const ALGORITHM = 'aes-256-cbc';

const ROOT_DIR = path.resolve(__dirname, '..');
const SOLUTIONS_SRC = path.join(ROOT_DIR, '..', 'scripts', 'solutions');
const WORDLISTS_SRC = path.join(ROOT_DIR, '..', 'scripts', 'wordlists');

// Output to both the generic assets dir and Android's assets dir
const ASSETS_DIR = path.join(ROOT_DIR, 'assets');
const ANDROID_ASSETS_DIR = path.join(ROOT_DIR, 'android', 'app', 'src', 'main', 'assets');

const SOLUTIONS_DEST = path.join(ASSETS_DIR, 'solutions');
const WORDLISTS_DEST = path.join(ASSETS_DIR, 'wordlists');
const ANDROID_SOLUTIONS_DEST = path.join(ANDROID_ASSETS_DIR, 'solutions');
const ANDROID_WORDLISTS_DEST = path.join(ANDROID_ASSETS_DIR, 'wordlists');

function encrypt(text) {
  const iv = crypto.randomBytes(16);
  const key = Buffer.from(ENCRYPTION_KEY, 'hex');
  const cipher = crypto.createCipheriv(ALGORITHM, key, iv);
  let encrypted = cipher.update(text, 'utf8', 'base64');
  encrypted += cipher.final('base64');
  // Prepend IV (base64) separated by a colon
  return iv.toString('base64') + ':' + encrypted;
}

function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, {recursive: true});
  }
}

function encryptSolutions() {
  ensureDir(SOLUTIONS_DEST);
  ensureDir(ANDROID_SOLUTIONS_DEST);

  const files = fs.readdirSync(SOLUTIONS_SRC).filter(f => f.endsWith('.txt'));
  console.log(`Encrypting ${files.length} solution file(s)...`);

  for (const file of files) {
    const srcPath = path.join(SOLUTIONS_SRC, file);
    const content = fs.readFileSync(srcPath, 'utf8');
    const encrypted = encrypt(content);
    const encFilename = file.replace('.txt', '.enc');

    fs.writeFileSync(path.join(SOLUTIONS_DEST, encFilename), encrypted, 'utf8');
    fs.writeFileSync(path.join(ANDROID_SOLUTIONS_DEST, encFilename), encrypted, 'utf8');
    console.log(`  ${file} -> ${encFilename}`);
  }
}

function copyWordlists() {
  ensureDir(WORDLISTS_DEST);
  ensureDir(ANDROID_WORDLISTS_DEST);

  const files = fs.readdirSync(WORDLISTS_SRC).filter(f => f.endsWith('.txt'));
  console.log(`Copying ${files.length} wordlist file(s)...`);

  for (const file of files) {
    const srcPath = path.join(WORDLISTS_SRC, file);
    fs.copyFileSync(srcPath, path.join(WORDLISTS_DEST, file));
    fs.copyFileSync(srcPath, path.join(ANDROID_WORDLISTS_DEST, file));
    console.log(`  ${file}`);
  }

  // Generate a JS module that embeds wordlists for reliable Metro bundling
  const generatedDir = path.join(ROOT_DIR, 'src', 'generated');
  ensureDir(generatedDir);

  const wordlistEntries = [];
  for (const file of files) {
    const srcPath = path.join(WORDLISTS_SRC, file);
    const words = fs.readFileSync(srcPath, 'utf8')
      .split('\n')
      .map(w => w.trim())
      .filter(w => w.length > 0);
    const key = file.replace('.txt', '');
    wordlistEntries.push(`  '${key}': ${JSON.stringify(words)}`);
  }

  const moduleContent = `// Auto-generated by scripts/encrypt-solutions.js — do not edit manually
const WORDLISTS: Record<string, string[]> = {\n${wordlistEntries.join(',\n')}\n};\n\nexport default WORDLISTS;\n`;
  fs.writeFileSync(path.join(generatedDir, 'wordlists.ts'), moduleContent, 'utf8');
  console.log('  Generated src/generated/wordlists.ts');
}

function main() {
  console.log('Preparing app assets...\n');

  if (!fs.existsSync(SOLUTIONS_SRC)) {
    console.error(`ERROR: Solutions directory not found: ${SOLUTIONS_SRC}`);
    process.exit(1);
  }
  if (!fs.existsSync(WORDLISTS_SRC)) {
    console.error(`ERROR: Wordlists directory not found: ${WORDLISTS_SRC}`);
    process.exit(1);
  }

  encryptSolutions();
  console.log('');
  copyWordlists();
  console.log('\nDone!');
}

main();
